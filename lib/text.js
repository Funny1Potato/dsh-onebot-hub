/**
 * 注入文本的单行化（`m08997` 用户在最新会话日志里发现的换行问题）。
 *
 * ## 为什么不能"直接压成空格"
 * 聊天消息本身带换行（模型一次 `onebot_reply` 里写了 `清单：\n【消息与会话】…`），
 * 入库存的是**带换行的原文**（`recall/*.jsonl` 里能查回 `\n`）。但注入文本要"一条消息一行"，
 * 于是各渲染层自己做单行化——问题出在**做法不一致**：
 *
 *   - `#batchLines`（`Mind`）：换行 → ` ⏎ `（保留信息）
 *   - `#openingText` 卡行 / `renderWindow` / `renderDigest` / `noteDownstreamSend`：
 *     `replace(/\s+/g,' ')`（**换行直接消失**）
 *
 * 结果同一条消息在【新消息】里是"…： ⏎ 【消息与会话】…"，到了开局快照/窗口/恢复卡里
 * 就变成"…： 【消息与会话】…"，五个【分组】被挤成一条 200 多字的单行——清单型消息最惨。
 *
 * ## 为什么是 `⏎` 而不是真换行
 * 真换行会让**一条**消息在注入文本里裂成多行，那它就能伪造出 `- ` 列表项、
 * `【短期记忆】` 这类段标题，是实打实的注入面。`⏎` 既保住了"这里断过行"的信息，
 * 又不改变注入文本的结构——一行还是那条消息。
 */

/**
 * 单行化消息正文：换行（含 `\r\n`）渲染成 ` ⏎ `，行内连续空白压成一个空格。
 * @param {unknown} text
 * @returns {string}
 */
export function flatBreaks(text) {
  return String(text ?? '')
    .replace(/\s*\n\s*/g, ' ⏎ ')
    .replace(/\s+/g, ' ')
    .trim();
}
